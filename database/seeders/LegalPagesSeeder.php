<?php

/**
 * Seeds the two legal pages the footer links to, using the wording from the
 * Next.js version so the footer links do not 404.
 * They live in static_pages so the admin can edit them later.
 */

require 'D:/2/vendor/autoload.php';
$app = require_once 'D:/2/bootstrap/app.php';
$app->make(Illuminate\Contracts\Console\Kernel::class)->bootstrap();

use Illuminate\Support\Facades\DB;

function h(string $t): string
{
    return '<h2 class="text-lg font-bold text-[#1B365D] mt-6 mb-3">' . $t . '</h2>';
}

function p(string $t): string
{
    return '<p class="mt-3 text-justify">' . $t . '</p>';
}

$privacy = implode("\n", [
