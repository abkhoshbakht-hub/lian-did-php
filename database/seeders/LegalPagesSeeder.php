    p('در بازدید از پایگاه خبری لیان دید، اطلاعاتی که به‌صورت خودکار و بدون نیاز به ثبت‌نام ثبت می‌شوند شامل نشانی IP، نوع مرورگر و صفحات بازدیدشده است. این اطلاعات صرفاً برای بهبود کیفیت خدمات و آمار بازدید استفاده می‌شود و در اختیار شخص ثالث قرار نمی‌گیرد.'),
