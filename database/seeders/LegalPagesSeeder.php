$pages = [
    [
        'slug'     => 'privacy',
        'title'    => 'حریم خصوصی',
        'excerpt'  => 'سیاست حفظ حریم خصوصی پایگاه خبری لیان دید',
        'content'  => $privacy,
    ],
    [
        'slug'     => 'terms',
        'title'    => 'قوانین و مقررات',
        'excerpt'  => 'شرایط استفاده از پایگاه خبری لیان دید',
        'content'  => $terms,
    ],
];

foreach ($pages as $p) {
    $exists = DB::table('static_pages')->where('slug', $p['slug'])->exists();

    if ($exists) {
        echo "  skip {$p['slug']} (already exists)\n";

        continue;
    }

    DB::table('static_pages')->insert([
        'id'         => 'seed'.substr(md5($p['slug']), 0, 21),
        'slug'       => $p['slug'],
        'title'      => $p['title'],
        'excerpt'    => $p['excerpt'],
        'content'    => $p['content'],
        'authorName' => 'لیان دید',
        'created_at' => now(),
        'updated_at' => now(),
    ]);

    echo "  created {$p['slug']} (".mb_strlen($p['content'])." chars)\n";
}

echo "done\n";